create or replace function public.ica_preview_credential_no(p_issuer_code text,p_type_code text)
returns text
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
declare r record;
begin
  if not (select private.ica_is_admin()) then raise exception 'ICA_ADMIN_REQUIRED'; end if;
  select nr.* into r
  from public.ica_number_rules nr
  join public.ica_issuers i on i.id=nr.issuer_id
  join public.ica_credential_types t on t.id=nr.credential_type_id
  where i.code=upper(btrim(p_issuer_code)) and t.code=upper(btrim(p_type_code)) and nr.is_active;
  if not found then raise exception 'NUMBER_RULE_NOT_FOUND'; end if;
  return r.prefix||r.separator||lpad(r.next_value::text,r.digits,'0');
end;
$$;
revoke all on function public.ica_preview_credential_no(text,text) from public;
grant execute on function public.ica_preview_credential_no(text,text) to authenticated;

create or replace function public.ica_issue_credential(p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_issuer public.ica_issuers%rowtype;
  v_type public.ica_credential_types%rowtype;
  v_rule public.ica_number_rules%rowtype;
  v_id uuid;
  v_no text;
begin
  if auth.uid() is null or not private.ica_is_admin() then raise exception 'ICA_ADMIN_REQUIRED'; end if;
  select * into v_issuer from public.ica_issuers where code=upper(btrim(p_data->>'issuer_code')) and is_active;
  select * into v_type from public.ica_credential_types where code=upper(btrim(p_data->>'type_code')) and is_active;
  if v_issuer.id is null or v_type.id is null then raise exception 'INVALID_ISSUER_OR_TYPE'; end if;
  if nullif(btrim(p_data->>'person_name'),'') is null then raise exception 'PERSON_NAME_REQUIRED'; end if;

  select * into v_rule from public.ica_number_rules
  where issuer_id=v_issuer.id and credential_type_id=v_type.id and is_active
  for update;
  if v_rule.id is null then raise exception 'NUMBER_RULE_NOT_FOUND'; end if;
  v_no := v_rule.prefix||v_rule.separator||lpad(v_rule.next_value::text,v_rule.digits,'0');

  insert into public.ica_credentials(
    credential_no,issuer_id,credential_type_id,detail_type_id,detail_label,person_name,person_name_en,photo_url,
    qualification_name,discipline,rank_grade,position_title,issued_on,valid_until,phone,email,postal_code,address,
    address_detail,admin_note,status,card_requested,document_requested,created_by
  ) values (
    v_no,v_issuer.id,v_type.id,nullif(p_data->>'detail_type_id','')::uuid,nullif(btrim(p_data->>'detail_label'),''),
    btrim(p_data->>'person_name'),nullif(btrim(p_data->>'person_name_en'),''),nullif(btrim(p_data->>'photo_url'),''),
    nullif(btrim(p_data->>'qualification_name'),''),nullif(btrim(p_data->>'discipline'),''),nullif(btrim(p_data->>'rank_grade'),''),
    nullif(btrim(p_data->>'position_title'),''),coalesce(nullif(p_data->>'issued_on','')::date,current_date),
    nullif(p_data->>'valid_until','')::date,nullif(btrim(p_data->>'phone'),''),nullif(btrim(p_data->>'email'),''),
    nullif(btrim(p_data->>'postal_code'),''),nullif(btrim(p_data->>'address'),''),nullif(btrim(p_data->>'address_detail'),''),
    nullif(btrim(p_data->>'admin_note'),''),'VALID',coalesce((p_data->>'card_requested')::boolean,v_type.default_card),
    coalesce((p_data->>'document_requested')::boolean,v_type.default_document),auth.uid()
  ) returning id into v_id;

  update public.ica_number_rules set next_value=next_value+1,updated_at=now() where id=v_rule.id;
  insert into public.ica_status_history(credential_id,old_status,new_status,reason,changed_by)
  values(v_id,null,'VALID','INITIAL_ISSUE',auth.uid());
  return jsonb_build_object('id',v_id,'credential_no',v_no);
end;
$$;
revoke all on function public.ica_issue_credential(jsonb) from public;
grant execute on function public.ica_issue_credential(jsonb) to authenticated;

create or replace function public.ica_change_status(p_credential_id uuid,p_new_status text,p_reason text default null)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare old_value text; new_value text:=upper(btrim(p_new_status));
begin
  if auth.uid() is null or not private.ica_is_admin() then raise exception 'ICA_ADMIN_REQUIRED'; end if;
  if new_value not in ('VALID','EXPIRED','SUSPENDED','REVOKED') then raise exception 'INVALID_STATUS'; end if;
  select status into old_value from public.ica_credentials where id=p_credential_id for update;
  if old_value is null then raise exception 'CREDENTIAL_NOT_FOUND'; end if;
  update public.ica_credentials set status=new_value,updated_at=now() where id=p_credential_id;
  insert into public.ica_status_history(credential_id,old_status,new_status,reason,changed_by)
  values(p_credential_id,old_value,new_value,nullif(btrim(p_reason),''),auth.uid());
end;
$$;
revoke all on function public.ica_change_status(uuid,text,text) from public;
grant execute on function public.ica_change_status(uuid,text,text) to authenticated;

create or replace function public.ica_record_reissue(p_credential_id uuid,p_reason text)
returns bigint
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare v_id bigint;
begin
  if auth.uid() is null or not private.ica_is_admin() then raise exception 'ICA_ADMIN_REQUIRED'; end if;
  if not exists(select 1 from public.ica_credentials where id=p_credential_id) then raise exception 'CREDENTIAL_NOT_FOUND'; end if;
  insert into public.ica_reissues(credential_id,reason,processed_by) values(p_credential_id,btrim(p_reason),auth.uid()) returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.ica_record_reissue(uuid,text) from public;
grant execute on function public.ica_record_reissue(uuid,text) to authenticated;

create or replace function public.ica_verify_credential(p_credential_no text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare q text:=upper(btrim(p_credential_no)); result jsonb;
begin
  if q='' then return null; end if;
  select jsonb_build_object(
    'source','ICA','status',c.status,'credential_no',c.credential_no,'person_name',c.person_name,
    'person_name_en',c.person_name_en,'issuer_code',i.code,'issuer_name',i.name_ko,'issuer_name_en',i.name_en,
    'type_code',t.code,'type_name',t.name_ko,'detail_name',coalesce(d.name_ko,c.detail_label),
    'qualification_name',c.qualification_name,'discipline',c.discipline,'rank_grade',c.rank_grade,
    'position_title',c.position_title,'issued_on',c.issued_on,'valid_until',c.valid_until,
    'verified_by','ICA'
  ) into result
  from public.ica_credentials c join public.ica_issuers i on i.id=c.issuer_id
  join public.ica_credential_types t on t.id=c.credential_type_id
  left join public.ica_detail_types d on d.id=c.detail_type_id
  where upper(c.credential_no)=q;
  if result is not null then return result; end if;

  select jsonb_build_object(
    'source','LEGACY','status','VALID','credential_no',l.certificate_no,'person_name',l.name,'person_name_en',l.name_en,
    'issuer_code',l.organization_code,
    'issuer_name',case when l.organization_code='WTKF' then '세계태권검도연맹' else '국제경찰무도연합회' end,
    'type_code','DAN',
    'type_name',case when l.organization_code='WTKF' then '태권검도 단증' when l.certificate_no ilike '%경호무술%' then '경호무술 단증' else '경찰무도 단증' end,
    'rank_grade',case when l.rank_no is null then null else l.rank_no::text||'단' end,
    'issued_on',l.issued_at,'valid_until',null,'verified_by','ICA'
  ) into result
  from public.gms_legacy_members l where upper(btrim(l.certificate_no))=q limit 1;
  return result;
end;
$$;
revoke all on function public.ica_verify_credential(text) from public;
grant execute on function public.ica_verify_credential(text) to anon,authenticated;

