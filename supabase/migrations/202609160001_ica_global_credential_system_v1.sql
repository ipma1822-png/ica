create table if not exists public.ica_credential_types (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-Z]{3}$'),
  name_ko text not null,
  name_en text,
  default_card boolean not null default true,
  default_document boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ica_detail_types (
  id uuid primary key default gen_random_uuid(),
  credential_type_id uuid not null references public.ica_credential_types(id),
  issuer_id uuid references public.ica_issuers(id),
  code text,
  name_ko text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
