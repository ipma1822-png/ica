create table if not exists public.ica_status_history (
  id bigint generated by default as identity primary key,
  credential_id uuid not null references public.ica_credentials(id) on delete cascade,
  old_status text,
  new_status text not null check (new_status in ('VALID','EXPIRED','SUSPENDED','REVOKED')),
  reason text,
  changed_by uuid not null default auth.uid() references auth.users(id),
  changed_at timestamptz not null default now()
