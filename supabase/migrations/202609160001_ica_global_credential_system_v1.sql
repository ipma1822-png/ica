create table if not exists public.ica_number_rules (
  id uuid primary key default gen_random_uuid(),
  issuer_id uuid not null references public.ica_issuers(id),
  credential_type_id uuid not null references public.ica_credential_types(id),
  prefix text not null,
  separator text not null default '-',
  next_value bigint not null check (next_value > 0),
  digits smallint not null default 6 check (digits between 1 and 18),
  is_legacy_continuation boolean not null default false,
  is_active boolean not null default true,
  updated_at timestamptz not null default now(),
  unique (issuer_id, credential_type_id)
);

create table if not exists public.ica_credentials (
  id uuid primary key default gen_random_uuid(),
  credential_no text not null unique,
  issuer_id uuid not null references public.ica_issuers(id),
  credential_type_id uuid not null references public.ica_credential_types(id),
  detail_type_id uuid references public.ica_detail_types(id),
  detail_label text,
  person_name text not null,
  person_name_en text,
  photo_url text,
  qualification_name text,
  discipline text,
  rank_grade text,
  position_title text,
  issued_on date not null default current_date,
  valid_until date,
  phone text,
  email text,
  postal_code text,
  address text,
  address_detail text,
  admin_note text,
  status text not null default 'VALID' check (status in ('VALID','EXPIRED','SUSPENDED','REVOKED')),
