create or replace function private.ica_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select exists (
    select 1
    from public.gms_admin_accounts a
    where a.auth_user_id = auth.uid()
      and a.is_active = true
      and a.role in ('founder','master','coadmin','admin')
  );
$$;
revoke all on function private.ica_is_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.ica_is_admin() to authenticated;

create table if not exists public.ica_issuers (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-Z0-9]{2,12}$'),
  name_ko text not null,
  name_en text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
